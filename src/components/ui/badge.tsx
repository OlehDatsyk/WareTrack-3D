import { cva, type VariantProps } from "class-variance-authority";
import { cn } from "@/lib/utils";

export const badgeVariants = cva(
  "inline-flex items-center gap-1 whitespace-nowrap rounded-md px-2 py-0.5 text-[11.5px] font-semibold leading-5 [&_svg]:size-3",
  {
    variants: {
      tone: {
        neutral: "bg-slate-100 text-slate-600",
        brand: "bg-brand-50 text-brand-700",
        success: "bg-success-soft text-green-700",
        warning: "bg-warning-soft text-amber-700",
        danger: "bg-danger-soft text-red-700",
        info: "bg-info-soft text-sky-700",
        sim: "bg-sim-soft text-violet-700",
        dark: "bg-ink text-white",
      },
    },
    defaultVariants: { tone: "neutral" },
  },
);

export type BadgeTone = NonNullable<VariantProps<typeof badgeVariants>["tone"]>;

export function Badge({
  className,
  tone,
  dot,
  children,
  ...props
}: React.ComponentProps<"span"> & VariantProps<typeof badgeVariants> & { dot?: boolean }) {
  return (
    <span className={cn(badgeVariants({ tone }), className)} {...props}>
      {dot && <span className="size-1.5 rounded-full bg-current opacity-80" />}
      {children}
    </span>
  );
}

/** Marks records generated by the demo simulation engine. */
export function SimBadge({ className }: { className?: string }) {
  return (
    <Badge tone="sim" className={cn("px-1.5 text-[10px] tracking-wide", className)} title="Generated by the demo simulation">
      SIM
    </Badge>
  );
}
